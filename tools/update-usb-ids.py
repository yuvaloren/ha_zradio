#!/usr/bin/env python3
"""update-usb-ids.py — rebuilds guest/lib/usb-ids.json: the USB ids Home Assistant's own integrations list for Zigbee
and Z-Wave sticks, plus what the kit adds (tools/usb-annotations.json: family, serial settings, which port of a
two-port adapter, and sticks Home Assistant's lists do not carry).

    python3 tools/update-usb-ids.py <home-assistant/core commit>      # e.g. the current head of the dev branch

Reads raw.githubusercontent.com/home-assistant/core/<commit>/homeassistant/components/<c>/manifest.json for the
components in COMPONENTS; the commit is recorded in the output. Home Assistant core is Apache-2.0; the ids are facts
about hardware. Stdlib only. Exit 1 when a manifest cannot be read (nothing is written then)."""
import json, os, sys, urllib.request

COMPONENTS = {"zha": "zigbee", "zwave_js": "zwave", "homeassistant_sky_connect": "zigbee", "homeassistant_connect_zbt2": "zigbee"}
HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    if len(sys.argv) != 2 or len(sys.argv[1]) < 7:
        print(__doc__); return 2
    commit = sys.argv[1]
    ann = json.load(open(os.path.join(HERE, "usb-annotations.json")))
    entries, used = [], set()
    for comp, kind in COMPONENTS.items():
        url = "https://raw.githubusercontent.com/home-assistant/core/%s/homeassistant/components/%s/manifest.json" % (commit, comp)
        try: m = json.load(urllib.request.urlopen(url, timeout=30))
        except Exception as e:
            print("FAIL  %s: %s" % (url, e), file=sys.stderr); return 1
        for u in m.get("usb", []):
            e = {"vid": u["vid"].upper(), "pid": u["pid"].upper(), "description": u.get("description", "*").lower(), "kind": kind,
                 "known_devices": u.get("known_devices", []), "source": "home-assistant:" + comp}
            if u.get("manufacturer"): e["manufacturer"] = u["manufacturer"].lower()
            key = "%s:%s %s" % (e["vid"], e["pid"], e["description"])
            a = ann["annotate"].get(key)
            if a: used.add(key)
            a = a or {}
            e["family"] = a.get("family", ""); e["baud"] = a.get("baud", 115200); e["flow"] = a.get("flow", "none")
            e["proven"] = bool(a.get("proven", False)); e["annotated"] = key in used
            for k in ("iface", "note"):
                if k in a: e[k] = a[k]
            if e not in entries: entries.append(e)
    unused = sorted(set(ann["annotate"]) - used)
    for a in ann["add"]:
        e = dict(a); e["vid"] = e["vid"].upper(); e["pid"] = e["pid"].upper(); e.setdefault("proven", False); e["annotated"] = True
        entries.append(e)
    out = {"format": "zradio usb ids v1", "home_assistant_core_commit": commit,
           "_comment": "Generated by tools/update-usb-ids.py; do not edit. 'description' is matched like Home Assistant matches it: a case-insensitive glob on the USB product string. proven=true: served, synced and failed over on real hardware by this project.",
           "entries": entries}
    path = os.path.join(HERE, "..", "guest", "lib", "usb-ids.json")
    json.dump(out, open(path + ".tmp", "w"), indent=1, sort_keys=True); os.replace(path + ".tmp", path)
    print("wrote %s: %d entries (%d from Home Assistant, %d added)" % (os.path.normpath(path), len(entries), len(entries) - len(ann["add"]), len(ann["add"])))
    for k in unused: print("WARN  annotation without a list entry (the list changed?): %s" % k)
    for e in entries:
        if not e["annotated"]: print("NOTE  no annotation (family unknown, 115200 8N1 assumed): %s:%s %s %s" % (e["vid"], e["pid"], e["description"], e["known_devices"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
